/*
 * Renders the golden-hour aerial scenes to assets/img/scenes/*.webp and writes
 * assets/js/scenes.js (gold boundary paths for the overlay).
 *
 *   node tools/scenes/render.js            # all scenes
 *   node tools/scenes/render.js plots farm # some scenes
 *
 * Needs Node, Playwright (Chromium) and ImageMagick (`convert`).
 */
const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "../..");
const OUT = path.join(ROOT, "assets/img/scenes");
const ALL = ["plots", "plots-b", "plots-close", "house", "ghats", "farm", "farm-b", "mango", "river", "coast", "plains", "highway", "hills", "tea"];
const names = process.argv.slice(2).length ? process.argv.slice(2) : ALL;

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const metaFile = path.join(ROOT, "assets/js/scenes.js");
  let meta = {};
  if (fs.existsSync(metaFile)) {
    const m = fs.readFileSync(metaFile, "utf8").match(/=\s*(\{[\s\S]*\});/);
    if (m) meta = JSON.parse(m[1]);
  }
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  for (const name of names) {
    await page.goto("file://" + path.join(__dirname, "render.html") + "?scene=" + name);
    await page.waitForFunction(() => window.__done, null, { timeout: 180000 });
    const scene = await page.evaluate(() => window.__scene);
    const png = await page.evaluate(() => document.getElementById("c").toDataURL("image/png"));
    const tmp = path.join(OUT, name + ".png");
    fs.writeFileSync(tmp, Buffer.from(png.split(",")[1], "base64"));
    execFileSync("convert", [tmp, "-filter", "Lanczos", "-resize", "1920x1200", "-quality", "78", path.join(OUT, name + ".webp")]);
    fs.unlinkSync(tmp);
    meta[name] = { gold: scene.gold, open: !!scene.open, horizon: scene.horizon };
    console.log(name, scene.ms + "ms", (fs.statSync(path.join(OUT, name + ".webp")).size / 1024 | 0) + "KB");
  }
  await browser.close();
  fs.writeFileSync(metaFile,
    "/* Generated by tools/scenes/render.js: gold boundary paths (1600×1000 viewBox) for each scene image. */\n" +
    "window.TLP_SCENES = " + JSON.stringify(meta, null, 1) + ";\n");
})();
